/* Имя RVTEST_CODE_BEGIN: RISC-V test — окружение теста RISC-V; код; начало. */
#define RVTEST_CODE_BEGIN                                               \
        /* Переключить текущую секцию; ax означает размещаемый в памяти исполняемый код (.text.trap, "ax", @progbits). */ \
        .section .text.trap, "ax", @progbits;                           \
